//
//  MiniClawiSH.m
//  MiniClaw
//
//  Boots the iSH (AArch64 guest / asbestos threaded-code interpreter) runtime
//  and adapts its process-exit signalling for ISHShellExecutor.
//
//  Boot order (critical — iSH is fragile about this, see requirement #5):
//    1. install SIGSEGV/SIGBUS/SIGABRT/SIGILL/SIGTRAP handlers  (asbestos CoW/TLB recovery)
//    2. mount_root(&fakefs, "<root>/data")                      (the fakefs database)
//    3. become_first_process()                                  (creates init / pid 1)
//    4. create essential /dev nodes + /dev/pts
//    5. install exit_hook / die_handler (post ProcessExitedNotification)
//    6. mount procfs + devptsfs
//    7. bind-mount host MiniClaw (Documents/MiniClaw) -> guest /var/MiniClaw
//
//  Each guest process runs on its own pthread (task_start), so no central
//  scheduler loop is required. become_first_process only needs to run once;
//  thereafter become_new_init_child works from any thread.
//

