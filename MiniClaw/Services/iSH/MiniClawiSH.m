#pragma mark - Thread-local JIT state (defined in libish_emu.a)

extern __thread volatile sig_atomic_t in_jit;
extern __thread volatile uint64_t jit_saved_pc;
extern __thread volatile uint64_t jit_last_host_fault;
extern __thread volatile uint64_t jit_last_x7;
extern __thread volatile uint64_t jit_last_x10;
extern __thread volatile int jit_crash_count;
extern void jit_crash_trampoline(void);

#pragma mark - Process-exit notification

NSString *const ProcessExitedNotification = @"ProcessExitedNotification";

#pragma mark - Signal handler (ARM64 asbestos CoW / TLB recovery)

static void crash_handler(int sig, siginfo_t *info, void *ctx) {
#if defined(__aarch64__) && defined(GUEST_ARM64)
    // Inside JIT code a SIGSEGV/SIGBUS means a stale TLB entry after a
    // copy-on-write fault. Recover by redirecting execution to the asm
    // crash trampoline, which returns INT_JIT_CRASH to the interpreter.
    if ((sig == SIGSEGV || sig == SIGBUS) && in_jit) {
        ucontext_t *uc = (ucontext_t *)ctx;

        // _cpu (struct cpu_state *) is passed in x1.
        uint64_t cpu_ptr = uc->uc_mcontext->__ss.__x[1];

        uint64_t x7  = uc->uc_mcontext->__ss.__x[7];
        uint64_t x10 = uc->uc_mcontext->__ss.__x[10];
        uint64_t guest_addr = (x7 - x10) & 0xffffffffffffULL;

        jit_last_host_fault = (uint64_t)info->si_addr;
        jit_last_x7 = x7;
        jit_last_x10 = x10;
        jit_crash_count++;

        // Determine read/write from the host ESR (bit 6, WnR).
        uint64_t esr = uc->uc_mcontext->__es.__esr;
        int was_write = (esr & 0x40) != 0;

        // Offsets come from the generated cpu-offsets.h (must match the
        // static libraries that were built). Do NOT hardcode these.
        *(uint64_t *)(cpu_ptr + CPU_segfault_addr)       = guest_addr;
        *(int *)(cpu_ptr + CPU_segfault_was_write)       = was_write;
        *(uint64_t *)(cpu_ptr + CPU_pc)                  = (uint64_t)jit_saved_pc;

        uint64_t exit_sp = *(uint64_t *)(cpu_ptr + LOCAL_jit_exit_sp);
        uc->uc_mcontext->__ss.__sp = exit_sp;

        uc->uc_mcontext->__ss.__pc = (uint64_t)jit_crash_trampoline;

        sigset_t unblock;
        sigemptyset(&unblock);
        sigaddset(&unblock, sig);
        sigprocmask(SIG_UNBLOCK, &unblock, NULL);
        return;
    }
#endif

    // Non-JIT host crash: log and terminate the process.
    char buf[512];
    int len;
    ucontext_t *uc = (ucontext_t *)ctx;
    len = snprintf(buf, sizeof(buf),
                   "\n=== MiniClaw iSH HOST CRASH: signal %d ===\nfault addr: %p\n", sig, info->si_addr);
    write(STDERR_FILENO, buf, len);
#if defined(__aarch64__)
    len = snprintf(buf, sizeof(buf),
                   "pc:  0x%llx\nlr:  0x%llx\nsp:  0x%llx\n"
                   "x0:  0x%llx\nx1:  0x%llx\nx7:  0x%llx\nx28: 0x%llx\n",
                   uc->uc_mcontext->__ss.__pc, uc->uc_mcontext->__ss.__lr,
                   uc->uc_mcontext->__ss.__sp,
                   uc->uc_mcontext->__ss.__x[0], uc->uc_mcontext->__ss.__x[1],
                   uc->uc_mcontext->__ss.__x[7], uc->uc_mcontext->__ss.__x[28]);
    write(STDERR_FILENO, buf, len);
#endif
    _exit(139);
}

static void install_signal_handlers(void) {
    static char altstack[SIGSTKSZ];
    stack_t ss = {.ss_sp = altstack, .ss_size = SIGSTKSZ};
    sigaltstack(&ss, NULL);

    struct sigaction sa = {0};
    sa.sa_sigaction = crash_handler;
    sa.sa_flags = SA_SIGINFO | SA_ONSTACK;
    sigaction(SIGSEGV, &sa, NULL);
    sigaction(SIGBUS, &sa, NULL);
    sigaction(SIGABRT, &sa, NULL);
    sigaction(SIGILL,  &sa, NULL);
    sigaction(SIGTRAP, &sa, NULL);
}

#pragma mark - Process exit / die hooks

// Dedicated serial queue for exit notifications.
// We do NOT post directly to the main queue from the exit hook because:
//   1. The hook runs under iSH kernel locks (pids_lock).
//   2. If the main thread is blocked in ISHShellExecutor.executeExecutable:
//      (e.g., waiting for become_new_init_child / do_execve / task_start),
//      dispatch_async(main_queue) can create a re-entrancy deadlock where
//      the main thread processes the notification while still inside the
//      execution path — causing EXC_BAD_ACCESS on _activeExecutions.
// An intermediate serial queue breaks this cycle safely.
static dispatch_queue_t _exitNotifyQueue;

static void mini_claw_exit_hook(struct task *task, int code) {
    pid_t pid = task->pid;
    // Stage through our serial queue first, then hop to main queue.
    // This guarantees the hook returns immediately (no kernel lock hold)
    // and the notification delivery is fully decoupled from the caller.
    dispatch_async(_exitNotifyQueue ?: dispatch_get_main_queue(), ^{
        dispatch_async(dispatch_get_main_queue(), ^{
            [[NSNotificationCenter defaultCenter] postNotificationName:ProcessExitedNotification
                                                                object:nil
                                                              userInfo:@{@"pid": @(pid),
                                                                         @"code": @(code)}];
        });
    });
}

static void mini_claw_die_handler(const char *msg) {
    NSString *message = [NSString stringWithFormat:@"iSH panic: %s", msg ?: ""];
    NSLog(@"%@", message);
}

#pragma mark - 会话文件隔离 path-translate hook

// 会话专属逻辑子目录（guest 内 /var/MiniClaw/<name>）。
static const char *kSessionPrefixes[] = {
    "/var/MiniClaw/workspace",
    "/var/MiniClaw/attachments",
    "/var/MiniClaw/browser",
    "/var/MiniClaw/offloads",
    NULL
};

// 仅接管会话命名空间路径；其余路径一律返回 false，交由静态 bind mount / rootfs。
// 这样 shared / skills / memory / mounts 与系统目录完全不受影响，且 hook 调用频率最低
// （绝大多数 open/stat/readdir 命中父 bind mount 或 rootfs，根本不会下探到 Swift）。
// fs_context=0（init / 系统进程）访问会话专属路径时交由 Swift 侧返回 false，
// 而宿主 Documents/MiniClaw/workspace 等真实目录并不存在，回落后落空 → ENOENT，
// 天然实现"禁止访问会话专属路径"。
static bool miniclaw_session_path_translate_hook(const char *guest_path,
                                                 uint64_t fs_context,
                                                 char *out_host_path,
                                                 size_t out_size) {
    // 会话命名空间的四个逻辑子目录（按 fs_context 路由到当前会话）。
    for (int i = 0; kSessionPrefixes[i] != NULL; i++) {
        size_t len = strlen(kSessionPrefixes[i]);
        if (strncmp(guest_path, kSessionPrefixes[i], len) == 0 &&
            (guest_path[len] == '/' || guest_path[len] == '\0')) {
            // 命中会话命名空间：交给 Swift 路由（处理 fs_context=0 拒绝 + UUID 映射 + 宿主路径）。
            return miniclaw_session_resolve_host_path(fs_context, guest_path, out_host_path, out_size);
        }
    }
    // 会话专属根目录：/var/MiniClaw/sessions/<uuid>/...（路径内自带 uuid，
    // 由 Swift 侧做"路径 uuid == fs_context 所属会话"的隔离校验，阻止跨会话越权）。
    {
        static const char *kSessionsPrefix = "/var/MiniClaw/sessions";
        size_t slen = strlen(kSessionsPrefix);
        if (strncmp(guest_path, kSessionsPrefix, slen) == 0 &&
            (guest_path[slen] == '/' || guest_path[slen] == '\0')) {
            return miniclaw_session_resolve_host_path(fs_context, guest_path, out_host_path, out_size);
        }
    }
    return false;
}

// 反向 path-translate hook：把宿主绝对路径（F_GETPATH 返回）反查回 guest 路径，
// 供 realfs_getpath() 在 ls / getcwd / 路径显示时使用。
// 仅命中会话隔离标记 MiniClaw-Sessions/<uuid>/<sub> 时返回 true，其余返回 false
// 交由静态 bind mount 表（/var/MiniClaw -> Documents/MiniClaw）或根兜底处理。
static bool miniclaw_session_path_reverse_hook(const char *host_path,
                                               char *out_guest_path,
                                               size_t out_size) {
    return miniclaw_session_reverse_host_path(host_path, out_guest_path, out_size);
}

#pragma mark - Boot

// 可重置 boot 守卫:用串行队列串行化所有 boot 操作,失败后可重试
// (取代原先不可重置的 dispatch_once —— 那会导致首次 boot 失败后永久失败)。
static BOOL                  g_booted    = NO;
static int                   g_bootError = 0;
static MiniClawiSHBootState  g_bootState = MiniClawiSHBootStateIdle;
static dispatch_queue_t      g_bootQueue;
static dispatch_once_t       g_bootQueueOnce;

static dispatch_queue_t bootQueue(void) {
    dispatch_once(&g_bootQueueOnce, ^{
        g_bootQueue = dispatch_queue_create("com.miniclaw.ish.boot", DISPATCH_QUEUE_SERIAL);
    });
    return g_bootQueue;
}

// 真正执行 boot。必须在 g_bootQueue 上串行调用,禁止并发。
// 成功返回 0 且 g_booted=YES;失败返回负 errno 且 g_booted 保持 NO(可重试)。
// 注意:iSH 不提供“卸载/复位”内核状态的能力,因此重试是 best-effort —— 正常
// 路径下 boot 不会失败,此逻辑仅用于从偶发失败中自愈,避免 App 启动即永久不可用。
static int do_boot(const char *rootfsPath) {
    // Create exit notification queue BEFORE anything else so the hook
    // is safe even if boot fails partway through.
    _exitNotifyQueue = dispatch_queue_create("com.miniclaw.ish.exit",
                                             DISPATCH_QUEUE_SERIAL);

    install_signal_handlers();

    // fakefs mount source is the `data` subdirectory of the rootfs.
    char dataPath[PATH_MAX];
    snprintf(dataPath, sizeof(dataPath), "%s/data", rootfsPath);

    int err = mount_root(&fakefs, dataPath);
    if (err < 0) {
        NSLog(@"[MiniClawiSH] mount_root failed: %d", err);
        return err;
    }

    err = become_first_process();
    if (err < 0) {
        NSLog(@"[MiniClawiSH] become_first_process failed: %d", err);
        return err;
    }
    current->thread = pthread_self();

    // Essential device nodes (only valid with fakefs).
    generic_mknodat(AT_PWD, "/dev/null",    S_IFCHR|0666, dev_make(MEM_MAJOR, DEV_NULL_MINOR));
    generic_mknodat(AT_PWD, "/dev/zero",    S_IFCHR|0666, dev_make(MEM_MAJOR, DEV_ZERO_MINOR));
    generic_mknodat(AT_PWD, "/dev/full",    S_IFCHR|0666, dev_make(MEM_MAJOR, DEV_FULL_MINOR));
    generic_mknodat(AT_PWD, "/dev/random",  S_IFCHR|0666, dev_make(MEM_MAJOR, DEV_RANDOM_MINOR));
    generic_mknodat(AT_PWD, "/dev/urandom", S_IFCHR|0666, dev_make(MEM_MAJOR, DEV_URANDOM_MINOR));
    generic_mknodat(AT_PWD, "/dev/tty",     S_IFCHR|0666, dev_make(TTY_ALTERNATE_MAJOR, DEV_TTY_MINOR));
    generic_mknodat(AT_PWD, "/dev/console", S_IFCHR|0666, dev_make(TTY_ALTERNATE_MAJOR, DEV_CONSOLE_MINOR));
    generic_mknodat(AT_PWD, "/dev/ptmx",    S_IFCHR|0666, dev_make(TTY_ALTERNATE_MAJOR, DEV_PTMX_MINOR));
    generic_mkdirat(AT_PWD, "/dev/pts", 0755);

    // Hook process exit so ISHShellExecutor can resolve completions.
    // Unlike the iSH CLI, we do NOT exit the host app when init exits.
    exit_hook = mini_claw_exit_hook;
    die_handler = mini_claw_die_handler;

    do_mount(&procfs, "proc", "/proc", "", 0);
    do_mount(&devptsfs, "devpts", "/dev/pts", "", 0);

    // 把宿主 MiniClaw 主目录（Documents/MiniClaw）挂进容器的 /var/MiniClaw，
    // 让容器内 Linux 程序（apk / shell / python…）无需复制即可与 App 共享文件。
    // 这与 Agent 文件工具的 /var/MiniClaw 虚拟路径指向同一份宿主物理目录，语义一致。
    // fakefs_bind_mount 会自动在容器 meta.db 创建挂载点、校验 host 路径存在；
    // 挂载失败不应阻断 boot（仅该路径不可用），故只记录日志。
    //
    // ⚠️ 重要：bind mount 的 symlink 机制（data/var/MiniClaw -> host）在某些环境下
    // 可能不被 path walk 正确跟随，导致 /var/MiniClaw 在 guest 中"不存在"，
    // 所有访问（含 hook 路径）在 VFS 层就被 ENOENT 拦截、根本到不了 fakefs_open。
    // 因此下面必须用 generic_mkdirat 在 guest meta.db 中预建目录节点作为保底：
    // 目录节点确保 path walk 能通过；hook 仍在 fakefs_open 中按 fs_context 做运行时路由。
    {
        NSFileManager *fm = NSFileManager.defaultManager;
        NSString *docs = NSSearchPathForDirectoriesInDomains(NSDocumentDirectory, NSUserDomainMask, YES).firstObject;
        NSString *hostMiniClaw = [docs stringByAppendingPathComponent:@"MiniClaw"];
        // 双保险：FileSystemManager 通常在启动期已建好该目录，这里再确保一次，避免 ENOENT。
        if (![fm fileExistsAtPath:hostMiniClaw]) {
            [fm createDirectoryAtPath:hostMiniClaw
               withIntermediateDirectories:YES attributes:nil error:nil];
        }
        const char *hostPath = hostMiniClaw.fileSystemRepresentation;
        int bindErr = fakefs_bind_mount("/var/MiniClaw", hostPath, /*read_only=*/false);
        if (bindErr < 0) {
            NSLog(@"[MiniClawiSH] bind mount /var/MiniClaw failed: %d (will use mkdir fallback)", bindErr);
        } else {
            NSLog(@"[MiniClawiSH] bind mount /var/MiniClaw -> %s ok", hostPath);
        }

        // 保底：在 guest 文件系统中创建 /var/MiniClaw 及会话子目录节点。
        // 即使 bind mount symlink 不可靠，path walk 也能通过这些目录；
        // 实际文件 I/O 仍由 fakefs_open 中的 hook 按 fs_context 路由到正确宿主位置。
        // 已存在时 mkdirat 静默返回 EEXIST（无害）。
        generic_mkdirat(AT_PWD, "/var/MiniClaw", 0755);
        generic_mkdirat(AT_PWD, "/var/MiniClaw/workspace", 0755);
        generic_mkdirat(AT_PWD, "/var/MiniClaw/attachments", 0755);
        generic_mkdirat(AT_PWD, "/var/MiniClaw/browser", 0755);
        generic_mkdirat(AT_PWD, "/var/MiniClaw/offloads", 0755);
        // 会话专属根目录节点 /var/MiniClaw/sessions：保证 path walk 能下探到
        // /var/MiniClaw/sessions/<uuid>；具体 <uuid> 由 hook 在运行时按 fs_context 路由。
        // 旧版本曾用大写 /var/MiniClaw/Sessions 作为会话根。iSH rootfs 大小写敏感且持久化，
        // 大写目录不会随改名自动消失，会与新建的小写 sessions 并存（ls 看到两个）。
        // 此处做一次性的大小写归一（rename 迁移，不删任何节点）：
        //   - 大写存在且小写不存在 → 直接改名；
        //   - 两者并存（极端情况）→ 小写已权威，大写仅含旧版孤儿占位，移除之。
        // 之后再保底 mkdir 小写（已存在则 EEXIST 无害）。
        if (generic_accessat(AT_PWD, "/var/MiniClaw/Sessions", F_OK) == 0) {
            if (generic_accessat(AT_PWD, "/var/MiniClaw/sessions", F_OK) != 0) {
                generic_renameat(AT_PWD, "/var/MiniClaw/Sessions", AT_PWD, "/var/MiniClaw/sessions");
            } else {
                generic_rmdirat(AT_PWD, "/var/MiniClaw/Sessions");
            }
        }
        generic_mkdirat(AT_PWD, "/var/MiniClaw/sessions", 0755);
        NSLog(@"[MiniClawiSH] guest /var/MiniClaw/* dirs ensured (mkdir fallback)");
    }

    // 立刻按当前挂载表对齐占位目录，保证 `ls /var/MiniClaw/mounts` 能列出挂载名。
    miniclaw_mount_placeholder_reconcile();
    // 触发双向镜像初始同步：外部文件夹 → 沙盒内 mounts/<name>/ 镜像目录，
    // iSH 后续访问走沙盒镜像路径（裸 open 沙盒目录必然成功，规避 File Provider 限制）。
    miniclaw_mount_mirror_initial_sync();

    // 注册会话文件隔离 hook：把 /var/MiniClaw/{workspace,attachments,browser,offloads}
    // 按 current->group->fs_context 路由到宿主 Documents/MiniClaw-Sessions/<uuid>/<subdir>。
    // shared/skills/memory/mounts 与系统目录不走 hook，仍用父 bind mount / rootfs。
    // hook 内部已做前缀过滤：仅会话命名空间路径才会下探到 Swift，热路径开销最低。
    fakefs_set_path_translate_hook(miniclaw_session_path_translate_hook);

    // 注册反向 hook：realfs_getpath() 在 F_GETPATH 反查时调用，把宿主
    // Documents/MiniClaw-Sessions/<uuid>/<sub>/... 翻译回 /var/MiniClaw/<sub>/...。
    // 不注册它，会话内 ls / getcwd 会把会话文件反查失败、落到根目录兜底
    // （此前"ls 列根目录"的根因）。反向 hook 不收 fs_context，按 host 路径唯一标识。
    fakefs_set_path_reverse_hook(miniclaw_session_path_reverse_hook);

    // ── DNS 配置：从 iOS 系统解析器读取当前 DNS 并写入 /etc/resolv.conf ──
    // 原版 iSH AppDelegate.boot 在此位置调用 [self configureDns]，
    // 用 res_ninit() 读系统 DNS → generic_open 写入 guest /etc/resolv.conf。
    // MiniClaw 自定义 do_boot 之前遗漏了这一步 → 每次 iSH 启动都没有 DNS →
    // pip/apt/curl 等全部报 "Temporary failure in name resolution"，
    // AI 不得不手动 echo nameserver > /etc/resolv.conf 才能恢复。
    // 此处复制原版逻辑，确保 iSH 启动后 DNS 立即可用。
    {
        struct __res_state _res;
        if (EXIT_SUCCESS == res_ninit(&_res)) {
            NSMutableString *rc = [NSMutableString new];
            // search domains
            if (_res.dnsrch[0] != NULL) {
                [rc appendString:@"search"];
                for (int i = 0; _res.dnsrch[i] != NULL; i++) {
                    [rc appendFormat:@" %s", _res.dnsrch[i]];
                }
                [rc appendString:@"\n"];
            }
            // nameserver addresses
            union res_sockaddr_union servers[NI_MAXSERV];
            int n = res_getservers(&_res, servers, NI_MAXSERV);
            char addr[NI_MAXHOST];
            NSMutableArray *systemDNS = [NSMutableArray new];
            for (int i = 0; i < n; i++) {
                if (servers[i].sin.sin_len == 0) continue;
                getnameinfo((struct sockaddr *)&servers[i].sin,
                            servers[i].sin.sin_len,
                            addr, sizeof(addr), NULL, 0, NI_NUMERICHOST);
                [systemDNS addObject:[NSString stringWithUTF8String:addr]];
            }
            // 公共 DNS 兜底（2026-08-08）：系统 DNS 常是内网路由器地址（如 192.168.x.x），
            // 在 iOS「本地网络」权限未授权时被系统静默拦截 → 解析超时 → wget/curl 报 bad address。
            // glibc 按 resolv.conf 顺序尝试 nameserver：内网 DNS 可达 → 用它（内网域名可解析）；
            // 不可达 → 配合下方 options timeout:1 attempts:1，1 秒内自动切公共 DNS，解析永不坏。
            // 不去重系统 DNS（保持语义），仅追加系统未提供的公共 DNS。
            static const char *fallbackDNS[] = {"223.5.5.5", "119.29.29.29", NULL};
            for (int i = 0; fallbackDNS[i] != NULL; i++) {
                NSString *fb = [NSString stringWithUTF8String:fallbackDNS[i]];
                BOOL dup = NO;
                for (NSString *existing in systemDNS) {
                    if ([existing isEqualToString:fb]) { dup = YES; break; }
                }
                if (!dup) [systemDNS addObject:fb];
            }
            for (NSString *ns in systemDNS) {
                [rc appendFormat:@"nameserver %@\n", ns];
            }
            // 快速失败：内网 DNS 不可达时 1 秒内切下一个 nameserver（默认 5s×2 太慢，会拖垮首轮解析）。
            [rc appendString:@"options timeout:1 attempts:1\n"];
            struct fd *fd = generic_open("/etc/resolv.conf",
                                          O_WRONLY_ | O_CREAT_ | O_TRUNC_, 0666);
            if (!IS_ERR(fd)) {
                fd->ops->write(fd, rc.UTF8String,
                              [rc lengthOfBytesUsingEncoding:NSUTF8StringEncoding]);
                fd_close(fd);
                NSLog(@"[MiniClawiSH] /etc/resolv.conf written (%zu bytes)",
                      [rc lengthOfBytesUsingEncoding:NSUTF8StringEncoding]);
            } else {
                NSLog(@"[MiniClawiSH] WARNING: failed to open /etc/resolv.conf");
            }
        } else {
            NSLog(@"[MiniClawiSH] WARNING: res_ninit() failed, DNS may not work");
        }
    }

    NSLog(@"[MiniClawiSH] runtime booted (AArch64 / asbestos)");
    return 0;
}

/// 异步预热 boot(App 首次打开调用,不阻塞启动)。
/// 严格串行在 g_bootQueue 上:已成功则跳过;进行中/之前失败都重新尝试。
void MiniClawiSHPrewarmBoot(const char *rootfsPath) {
    dispatch_async(bootQueue(), ^{
        if (g_booted) { g_bootState = MiniClawiSHBootStateBooted; return; }
        g_bootState = MiniClawiSHBootStatePrewarming;
        int err = do_boot(rootfsPath);
        g_bootError = err;
        g_booted = (err >= 0);
        g_bootState = (err >= 0) ? MiniClawiSHBootStateBooted : MiniClawiSHBootStateFailed;
        if (err < 0) {
            NSLog(@"[MiniClawiSH] prewarm boot failed: %d (will retry on next execute)", err);
        }
    });
}

/// 同步确保 runtime 已启动(boot 惰性触发 / 命令执行前调用)。
/// - 已成功:立即返回 0。
/// - 预热进行中:阻塞等待其完成(命令必须等内核就绪)。
/// - 之前失败或未开始:同步重试一次(可重置守卫的核心价值)。
int MiniClawiSHEnsureBooted(const char *rootfsPath) {
    __block int result = 0;
    dispatch_sync(bootQueue(), ^{
        if (g_booted) { g_bootState = MiniClawiSHBootStateBooted; result = 0; return; }
        g_bootState = MiniClawiSHBootStatePrewarming;
        int err = do_boot(rootfsPath);
        g_bootError = err;
        g_booted = (err >= 0);
        g_bootState = (err >= 0) ? MiniClawiSHBootStateBooted : MiniClawiSHBootStateFailed;
        result = err;
    });
    return result;
}

BOOL MiniClawiSHIsBooted(void) {
    return g_booted;
}

MiniClawiSHBootState MiniClawiSHGetBootState(void) {
    return g_bootState;
}
